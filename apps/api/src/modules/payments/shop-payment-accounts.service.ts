import { randomBytes } from 'node:crypto';
import { HttpStatus, Inject, Injectable, Logger } from '@nestjs/common';
import {
  type ShopPaymentReadiness,
  type ShopPaymentSetup,
  type ShopPhonePairing,
  type UpdateShopPaymentSetupRequest,
} from '@kagaz/shared';
import { type Actor, actorMetadata } from '../../common/actor.js';
import { APP_CONFIG } from '../../common/config/config.module.js';
import { type AppConfig } from '../../common/config/config.schema.js';
import { SealedBox } from '../../common/crypto/sealed-box.js';
import { AppError } from '../../common/http/api-exception.filter.js';
import { PrismaService } from '../../common/prisma/prisma.service.js';
import { type ShopPaymentAccount } from '../../generated/prisma/client.js';
import { YoupiClient, YoupiError } from './providers/youpi/youpi-client.js';
import { type YoupiAccount, type YoupiAccountResolver } from './providers/youpi/youpi.provider.js';

/** DI token for the YouPI HTTP client (null unless PAYMENT_PROVIDER=youpi). */
export const YOUPI_CLIENT = Symbol('YOUPI_CLIENT');

/** A paired phone counts as online if it reported within this window. */
export const PHONE_ONLINE_WINDOW_MS = 5 * 60 * 1000;

interface SealedCredentials {
  apiKey: string;
  webhookSecret: string;
}

const aad = (shopId: string) => `shop-payment-account:${shopId}`;

/**
 * ADR-003 shop payment setup (P6.4) and the per-shop credential resolver for YoupiProvider.
 *
 * Shopkeeper does two things: saves a UPI ID, then scans a QR with their phone. Everything else
 * (YouPI merchant, API key, webhook secret, webhook URL, active VPA) is done here. Credentials
 * are generated by Kagaz, sealed with PAYMENT_SECRETS_KEY and never returned by any endpoint.
 */
@Injectable()
export class ShopPaymentAccountsService implements YoupiAccountResolver {
  private readonly logger = new Logger(ShopPaymentAccountsService.name);
  private readonly box: SealedBox | null;

  constructor(
    private readonly prisma: PrismaService,
    @Inject(APP_CONFIG) private readonly config: AppConfig,
    @Inject(YOUPI_CLIENT) private readonly youpi: YoupiClient | null,
  ) {
    this.box = config.PAYMENT_SECRETS_KEY ? new SealedBox(config.PAYMENT_SECRETS_KEY) : null;
  }

  private get usesYoupi(): boolean {
    return this.config.PAYMENT_PROVIDER === 'youpi' && this.youpi !== null;
  }

  // ─── Shop app endpoints ───

  async getSetup(shopId: string): Promise<ShopPaymentSetup> {
    const account = await this.prisma.shopPaymentAccount.findUnique({ where: { shopId } });
    if (!this.usesYoupi) {
      return {
        provider: this.config.PAYMENT_PROVIDER,
        readiness: 'NOT_REQUIRED',
        upiId: account?.upiId ?? null,
        payeeName: account?.payeeName ?? null,
        phones: [],
        appDownloadUrl: null,
        updatedAt: account?.updatedAt.toISOString() ?? null,
      };
    }

    let phones: ShopPaymentSetup['phones'] = [];
    let phonesKnown = true;
    if (account?.externalMerchantId) {
      try {
        const now = Date.now();
        phones = (await this.youpi!.devices(account.externalMerchantId))
          .filter((d) => d.isActive)
          .map((d) => ({
            id: d.id,
            name: d.name,
            lastSeenAt: d.lastHeartbeatAt,
            lastPaymentSeenAt: d.lastObservationAt,
            online:
              d.lastHeartbeatAt !== null &&
              now - new Date(d.lastHeartbeatAt).getTime() < PHONE_ONLINE_WINDOW_MS,
          }));
      } catch (err) {
        phonesKnown = false;
        this.logger.warn({ shopId, err: describe(err) }, 'YouPI device status unavailable');
      }
    }

    return {
      provider: 'youpi',
      readiness: readinessOf(account, phones, phonesKnown),
      upiId: account?.upiId ?? null,
      payeeName: account?.payeeName ?? null,
      phones,
      appDownloadUrl: YoupiClient.apkUrl(
        this.config.YOUPI_PUBLIC_URL ?? this.config.YOUPI_API_URL!,
      ),
      updatedAt: account?.updatedAt.toISOString() ?? null,
    };
  }

  /**
   * Step 1 — save the UPI ID. First save provisions the shop's YouPI merchant; later saves
   * switch the active VPA. Idempotent for the same values. Serialised per shop (advisory lock),
   * so a double-click never creates two merchants.
   */
  async saveSetup(
    shopId: string,
    req: UpdateShopPaymentSetupRequest,
    actor: Actor,
  ): Promise<ShopPaymentSetup> {
    if (!this.usesYoupi) {
      throw new AppError(
        'PAYMENT_SETUP_NOT_REQUIRED',
        'This environment uses demo payments; there is nothing to set up.',
        HttpStatus.CONFLICT,
      );
    }
    const box = this.requireBox();
    await this.prisma.$transaction(
      async (tx) => {
        await tx.$executeRaw`SELECT pg_advisory_xact_lock(hashtext(${`shop-payment-setup:${shopId}`}))`;
        const shop = await tx.shop.findUniqueOrThrow({
          where: { id: shopId },
          select: { slug: true },
        });
        const existing = await tx.shopPaymentAccount.findUnique({ where: { shopId } });
        const before = existing ? { upiId: existing.upiId, payeeName: existing.payeeName } : null;

        let externalMerchantId = existing?.externalMerchantId ?? null;
        let credentialsSealed = existing?.credentialsSealed ?? null;
        if (!externalMerchantId || !credentialsSealed) {
          const creds: SealedCredentials = {
            apiKey: `yp_live_${randomBytes(16).toString('hex')}`,
            webhookSecret: randomBytes(32).toString('hex'),
          };
          externalMerchantId = await this.provisionMerchant(shop.slug, req, creds);
          credentialsSealed = box.seal(JSON.stringify(creds), aad(shopId));
        } else if (before?.upiId !== req.upiId || before?.payeeName !== req.payeeName) {
          await this.switchVpa(externalMerchantId, req);
        }

        await tx.shopPaymentAccount.upsert({
          where: { shopId },
          create: {
            shopId,
            provider: 'youpi',
            upiId: req.upiId,
            payeeName: req.payeeName,
            externalMerchantId,
            credentialsSealed,
          },
          update: {
            provider: 'youpi',
            upiId: req.upiId,
            payeeName: req.payeeName,
            externalMerchantId,
            credentialsSealed,
          },
        });
        await tx.auditLog.create({
          data: {
            actorType: actor.type,
            actorId: actor.id,
            shopId,
            action: 'shop.payment_setup_saved',
            metadata: {
              provider: 'youpi',
              before,
              after: { upiId: req.upiId, payeeName: req.payeeName },
              ...actorMetadata(actor),
            },
          },
        });
      },
      { timeout: Math.max(15_000, this.config.YOUPI_HTTP_TIMEOUT_MS * 4) },
    );
    return this.getSetup(shopId);
  }

  /** Step 2 — short-lived pairing code for the YouPI phone app (shown as a QR). Audited. */
  async pairing(shopId: string, actor: Actor): Promise<ShopPhonePairing> {
    const account = await this.prisma.shopPaymentAccount.findUnique({ where: { shopId } });
    if (!this.usesYoupi || !account?.externalMerchantId) {
      throw new AppError(
        'PAYMENT_SETUP_REQUIRED',
        'Save your UPI ID first, then connect your phone.',
        HttpStatus.CONFLICT,
      );
    }
    const pairing = await this.call(() => this.youpi!.pairingPayload(account.externalMerchantId!));
    await this.prisma.auditLog.create({
      data: {
        actorType: actor.type,
        actorId: actor.id,
        shopId,
        action: 'shop.payment_phone_pairing_shown',
        metadata: { expiresAt: pairing.expiresAt.toISOString(), ...actorMetadata(actor) },
      },
    });
    return { qrText: pairing.qrText, expiresAt: pairing.expiresAt.toISOString() };
  }

  /** True when customers can pay this shop online right now (checkout guard). */
  async canTakePayments(shopId: string): Promise<boolean> {
    if (!this.usesYoupi) return true;
    const account = await this.prisma.shopPaymentAccount.findUnique({
      where: { shopId },
      select: { externalMerchantId: true, credentialsSealed: true },
    });
    return Boolean(account?.externalMerchantId && account.credentialsSealed);
  }

  // ─── YoupiAccountResolver ───

  async forShop(shopId: string): Promise<YoupiAccount> {
    const account = await this.prisma.shopPaymentAccount.findUnique({ where: { shopId } });
    const resolved = account ? this.unseal(account) : null;
    if (!resolved) {
      throw new AppError(
        'SHOP_PAYMENTS_NOT_SET_UP',
        'This shop cannot take online payments yet. Please pay at the counter or choose another shop.',
        HttpStatus.CONFLICT,
      );
    }
    return resolved;
  }

  async forProviderOrder(providerOrderId: string): Promise<YoupiAccount | null> {
    const payment = await this.prisma.payment.findFirst({
      where: { provider: 'youpi', providerOrderId },
      select: { order: { select: { shopId: true } } },
    });
    if (!payment) return null;
    const account = await this.prisma.shopPaymentAccount.findUnique({
      where: { shopId: payment.order.shopId },
    });
    return account ? this.unseal(account) : null;
  }

  // ─── internals ───

  private unseal(account: ShopPaymentAccount): YoupiAccount | null {
    if (account.provider !== 'youpi' || !account.externalMerchantId || !account.credentialsSealed) {
      return null;
    }
    const creds = JSON.parse(
      this.requireBox().open(account.credentialsSealed, aad(account.shopId)),
    ) as SealedCredentials;
    return {
      merchantId: account.externalMerchantId,
      apiKey: creds.apiKey,
      webhookSecret: creds.webhookSecret,
    };
  }

  private async provisionMerchant(
    shopSlug: string,
    req: UpdateShopPaymentSetupRequest,
    creds: SealedCredentials,
  ): Promise<string> {
    const webhookUrl = `${this.config.PUBLIC_API_URL!.replace(/\/+$/, '')}/webhooks/youpi`;
    const attempt = (slug: string) =>
      this.youpi!.createMerchant({
        businessName: req.payeeName,
        slug,
        webhookUrl,
        upiId: req.upiId,
        apiKey: creds.apiKey,
        webhookSecret: creds.webhookSecret,
      });
    try {
      return (await this.call(() => attempt(`kagaz-${shopSlug}`))).merchantId;
    } catch (err) {
      // A previous attempt created the merchant but our commit failed: we no longer hold its
      // keys, so start a fresh merchant (the orphan has no VPA traffic and can be removed).
      if (!(err instanceof AppError) || err.code !== 'PAYMENT_PROVIDER_CONFLICT') throw err;
      this.logger.warn({ shopSlug }, 'YouPI merchant slug taken — provisioning a new one');
      const suffix = randomBytes(3).toString('hex');
      return (await this.call(() => attempt(`kagaz-${shopSlug}-${suffix}`))).merchantId;
    }
  }

  private async switchVpa(merchantId: string, req: UpdateShopPaymentSetupRequest): Promise<void> {
    const accounts = await this.call(() => this.youpi!.listUpiAccounts(merchantId));
    const match = accounts.find((a) => a.upiId === req.upiId && a.payeeName === req.payeeName);
    const target =
      match ??
      (await this.call(() => this.youpi!.addUpiAccount(merchantId, req.upiId, req.payeeName)));
    if (!target.isActive) await this.call(() => this.youpi!.activateUpiAccount(target.id));
  }

  /** YouPI failures become a stable, retryable API error (no provider details leak). */
  private async call<T>(fn: () => Promise<T>): Promise<T> {
    try {
      return await fn();
    } catch (err) {
      if (err instanceof YoupiError && err.status === 409) {
        throw new AppError(
          'PAYMENT_PROVIDER_CONFLICT',
          'The payment service already has this record.',
          HttpStatus.CONFLICT,
        );
      }
      if (err instanceof YoupiError) {
        this.logger.error({ err: describe(err) }, 'YouPI call failed');
        throw new AppError(
          'PAYMENT_PROVIDER_UNAVAILABLE',
          'Could not reach the payment service. Please try again in a minute.',
          HttpStatus.BAD_GATEWAY,
          { providerStatus: err.status },
        );
      }
      throw err;
    }
  }

  private requireBox(): SealedBox {
    if (!this.box) throw new Error('PAYMENT_SECRETS_KEY is not configured');
    return this.box;
  }
}

export function readinessOf(
  account: Pick<ShopPaymentAccount, 'externalMerchantId'> | null,
  phones: readonly { online: boolean }[],
  phonesKnown: boolean,
): ShopPaymentReadiness {
  if (!account?.externalMerchantId) return 'NEEDS_UPI_ID';
  if (!phonesKnown) return 'PHONE_OFFLINE';
  if (phones.length === 0) return 'NEEDS_PHONE';
  return phones.some((p) => p.online) ? 'READY' : 'PHONE_OFFLINE';
}

function describe(err: unknown): string {
  return err instanceof Error ? `${err.name}: ${err.message}` : String(err);
}
